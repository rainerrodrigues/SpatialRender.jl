# A small stroke font for labels: every glyph is a few polylines on a 4 × 6
# grid (baseline y = 0, cap height y = 6), drawn by the anti-aliased line
# shader, so text needs no font files or rasteriser and stays sharp at any
# size. Lowercase letters render as small capitals.

const Stroke = Vector{NTuple{2, Float32}}

const GLYPHS = let G = Dict{Char, Vector{Stroke}}()
    g(c, strokes...) = (G[c] = [Stroke([(Float32(x), Float32(y)) for (x, y) in s]) for s in strokes])
    O = [(1, 0), (0, 1), (0, 5), (1, 6), (3, 6), (4, 5), (4, 1), (3, 0), (1, 0)]
    P = [(0, 0), (0, 6), (3, 6), (4, 5), (4, 4), (3, 3), (0, 3)]
    dot(x, y) = [(x, y), (x, y + 0.3)]
    g('0', O, [(0.6, 1), (3.4, 5)])
    g('1', [(1, 5), (2, 6), (2, 0)], [(1, 0), (3, 0)])
    g('2', [(0, 5), (1, 6), (3, 6), (4, 5), (4, 4), (0, 0), (4, 0)])
    g('3', [(0, 5), (1, 6), (3, 6), (4, 5), (4, 4), (3, 3), (4, 2), (4, 1), (3, 0), (1, 0), (0, 1)], [(1, 3), (3, 3)])
    g('4', [(3, 0), (3, 6), (0, 2), (4, 2)])
    g('5', [(4, 6), (0, 6), (0, 3), (3, 3), (4, 2), (4, 1), (3, 0), (0, 0)])
    g('6', [(3, 6), (1, 6), (0, 5), (0, 1), (1, 0), (3, 0), (4, 1), (4, 2), (3, 3), (0, 3)])
    g('7', [(0, 6), (4, 6), (1, 0)])
    g('8', [(1, 3), (0, 4), (0, 5), (1, 6), (3, 6), (4, 5), (4, 4), (3, 3), (1, 3), (0, 2), (0, 1), (1, 0), (3, 0), (4, 1), (4, 2), (3, 3)])
    g('9', [(4, 3), (1, 3), (0, 4), (0, 5), (1, 6), (3, 6), (4, 5), (4, 1), (3, 0), (1, 0)])
    g('A', [(0, 0), (0, 4), (2, 6), (4, 4), (4, 0)], [(0, 2), (4, 2)])
    g('B', [(0, 0), (0, 6), (3, 6), (4, 5), (4, 4), (3, 3), (0, 3)], [(3, 3), (4, 2), (4, 1), (3, 0), (0, 0)])
    g('C', [(4, 5), (3, 6), (1, 6), (0, 5), (0, 1), (1, 0), (3, 0), (4, 1)])
    g('D', [(0, 0), (0, 6), (3, 6), (4, 5), (4, 1), (3, 0), (0, 0)])
    g('E', [(4, 6), (0, 6), (0, 0), (4, 0)], [(0, 3), (3, 3)])
    g('F', [(4, 6), (0, 6), (0, 0)], [(0, 3), (3, 3)])
    g('G', [(4, 5), (3, 6), (1, 6), (0, 5), (0, 1), (1, 0), (3, 0), (4, 1), (4, 3), (2, 3)])
    g('H', [(0, 0), (0, 6)], [(4, 0), (4, 6)], [(0, 3), (4, 3)])
    g('I', [(1, 6), (3, 6)], [(2, 6), (2, 0)], [(1, 0), (3, 0)])
    g('J', [(4, 6), (4, 1), (3, 0), (1, 0), (0, 1)])
    g('K', [(0, 0), (0, 6)], [(4, 6), (0, 2)], [(1.3, 3.3), (4, 0)])
    g('L', [(0, 6), (0, 0), (4, 0)])
    g('M', [(0, 0), (0, 6), (2, 3), (4, 6), (4, 0)])
    g('N', [(0, 0), (0, 6), (4, 0), (4, 6)])
    g('O', O)
    g('P', P)
    g('Q', O, [(2, 2), (4, 0)])
    g('R', P, [(2, 3), (4, 0)])
    g('S', [(4, 5), (3, 6), (1, 6), (0, 5), (0, 4), (1, 3), (3, 3), (4, 2), (4, 1), (3, 0), (1, 0), (0, 1)])
    g('T', [(0, 6), (4, 6)], [(2, 6), (2, 0)])
    g('U', [(0, 6), (0, 1), (1, 0), (3, 0), (4, 1), (4, 6)])
    g('V', [(0, 6), (2, 0), (4, 6)])
    g('W', [(0, 6), (1, 0), (2, 4), (3, 0), (4, 6)])
    g('X', [(0, 6), (4, 0)], [(0, 0), (4, 6)])
    g('Y', [(0, 6), (2, 3), (4, 6)], [(2, 3), (2, 0)])
    g('Z', [(0, 6), (4, 6), (0, 0), (4, 0)])
    g('.', dot(2, 0))
    g(',', [(2, 0.5), (1.4, -1)])
    g(':', dot(2, 0.6), dot(2, 4))
    g(';', dot(2, 4), [(2, 0.5), (1.4, -1)])
    g('-', [(1, 3), (3, 3)])
    g('+', [(0.5, 3), (3.5, 3)], [(2, 1.5), (2, 4.5)])
    g('=', [(0.5, 2), (3.5, 2)], [(0.5, 4), (3.5, 4)])
    g('/', [(0, 0), (4, 6)])
    g('(', [(3, 6.5), (2, 5.3), (1.5, 3), (2, 0.7), (3, -0.5)])
    g(')', [(1, 6.5), (2, 5.3), (2.5, 3), (2, 0.7), (1, -0.5)])
    g('[', [(3, 6.5), (1.5, 6.5), (1.5, -0.5), (3, -0.5)])
    g(']', [(1, 6.5), (2.5, 6.5), (2.5, -0.5), (1, -0.5)])
    g('%', [(0, 0), (4, 6)], [(0, 6), (1, 6), (1, 5), (0, 5), (0, 6)], [(3, 1), (4, 1), (4, 0), (3, 0), (3, 1)])
    g('°', [(1, 6), (2.2, 6), (2.2, 4.8), (1, 4.8), (1, 6)])
    g('_', [(0, -1), (4, -1)])
    g('!', [(2, 6), (2, 2)], dot(2, 0))
    g('?', [(0, 5), (1, 6), (3, 6), (4, 5), (4, 4), (2, 3), (2, 2)], dot(2, 0))
    g('#', [(1, 0), (1, 6)], [(3, 0), (3, 6)], [(0, 2), (4, 2)], [(0, 4), (4, 4)])
    g('*', [(2, 1.5), (2, 4.5)], [(0.7, 2.2), (3.3, 3.8)], [(0.7, 3.8), (3.3, 2.2)])
    g('<', [(4, 5), (0, 3), (4, 1)])
    g('>', [(0, 5), (4, 3), (0, 1)])
    g('\'', [(2, 6), (2, 4.5)])
    g('"', [(1.3, 6), (1.3, 4.5)], [(2.7, 6), (2.7, 4.5)])
    g('Δ', [(0, 0), (2, 6), (4, 0), (0, 0)])
    g('±', [(0.5, 3.5), (3.5, 3.5)], [(2, 2), (2, 5)], [(0.5, 0.5), (3.5, 0.5)])
    g('×', [(0.7, 1.5), (3.3, 4.5)], [(0.7, 4.5), (3.3, 1.5)])
    G
end

const GLYPH_ADVANCE = 6f0      # units per character
const GLYPH_LINE = 9.5f0       # units per text line
const SMALL_CAPS = 0.72f0      # lowercase scale

"""
    text_segments(text) -> Vector{NTuple{2, Vec2f}}

Line segments (in glyph units, origin at the first baseline, y up, lines
going down) for `text`. Unknown characters render as `?`; `\\n` starts a
new line.
"""
function text_segments(text::AbstractString)
    out = NTuple{2, Vec2f}[]
    x = 0f0; y = 0f0
    for c in text
        if c == '\n'
            x = 0f0; y -= GLYPH_LINE; continue
        elseif c == ' '
            x += GLYPH_ADVANCE; continue
        end
        s = 1f0
        if islowercase(c)
            c = uppercase(c); s = SMALL_CAPS
        end
        strokes = get(GLYPHS, c, GLYPHS['?'])
        for st in strokes, i in 1:length(st)-1
            a, b = st[i], st[i+1]
            push!(out, (Vec2f(x + s * a[1], y + s * a[2]), Vec2f(x + s * b[1], y + s * b[2])))
        end
        x += GLYPH_ADVANCE * (s < 1 ? 0.85f0 : 1f0)
    end
    return out
end

"Width and height of `text` in glyph units."
function text_extent(text::AbstractString)
    lines = split(text, '\n')
    w = maximum(length, lines; init=0) * GLYPH_ADVANCE
    h = 6f0 + (length(lines) - 1) * GLYPH_LINE
    return Vec2f(w, h)
end
